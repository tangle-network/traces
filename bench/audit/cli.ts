#!/usr/bin/env node
/**
 * The benchmark runner.
 *
 *   tsx bench/audit/cli.ts fixtures --out <dir>
 *   tsx bench/audit/cli.ts gold --out <file.json>
 *   tsx bench/audit/cli.ts score <answers.json> [--fixtures <dir>] [--out <report.md>] [--json <score.json>]
 *   tsx bench/audit/cli.ts arm --arm facts|raw-files|traces --out <answers.json> [--model M --budget-usd B]
 *     [--questions id,id] [--variants canonical|all] [--concurrency N] [--fixtures <dir>] [--traces <cli.js>] [--work <dir>]
 *
 * `fixtures` writes the tree an arm is allowed to read: the synthetic sessions,
 * a manifest, and one prompt per question wording. The gold answers are written
 * only by `gold`, into a separate path, so an arm's working directory can hold
 * the sessions without holding the answer key.
 *
 * `score` is the whole grader. It compares an arm's answers JSON against the
 * gold by exact match, with no model in the loop, and it rebuilds the fixture
 * bytes itself: a `--fixtures` directory is accepted only when every file in it
 * matches the generated bytes, so an arm cannot be scored against a tree it
 * edited.
 *
 * `arm` answers every question wording with one arm (`arms.ts`) and writes the
 * answers file `score` reads.
 */

import { mkdtemp, mkdir, readFile, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ARMS, type ArmName, runArm } from './arms.js'
import { loadCitationIndex } from './citations.js'
import { generateBench, writeFixtures, type GeneratedBench } from './fixtures.js'
import { promptRows } from './questions.js'
import { parseAnswersFile, renderArmScore, scoreArm } from './score.js'

const USAGE = [
  'Usage:',
  '  bench/audit/cli.ts fixtures --out <dir>',
  '  bench/audit/cli.ts gold --out <file.json>',
  '  bench/audit/cli.ts score <answers.json> [--fixtures <dir>] [--out <report.md>] [--json <score.json>]',
  '  bench/audit/cli.ts arm --arm facts|raw-files|traces --out <answers.json> [--model M --budget-usd B]',
  '      [--questions id,id] [--variants canonical|all] [--concurrency N] [--fixtures <dir>] [--traces <cli.js>] [--work <dir>]',
].join('\n')

/** This checkout's built CLI. */
const DIST_CLI = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'dist', 'cli.js')

interface Args {
  positional: string[]
  flags: Map<string, string>
}

function parseArgs(argv: readonly string[]): Args {
  const positional: string[] = []
  const flags = new Map<string, string>()
  for (let index = 0; index < argv.length; index += 1) {
    const item = argv[index]!
    if (!item.startsWith('--')) {
      positional.push(item)
      continue
    }
    const equals = item.indexOf('=')
    if (equals > 0) {
      flags.set(item.slice(2, equals), item.slice(equals + 1))
      continue
    }
    const value = argv[index + 1]
    if (value === undefined || value.startsWith('--')) throw new Error(`${item} needs a value`)
    flags.set(item.slice(2), value)
    index += 1
  }
  return { positional, flags }
}

async function writeOut(path: string, content: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, content)
}

/** Every file the runner writes into an arm's directory, keyed by its relative path. */
function armInputs(bench: GeneratedBench): Map<string, string> {
  const inputs = new Map(bench.files.map((file) => [file.path, file.content]))
  inputs.set('manifest.json', `${JSON.stringify(bench.manifest, null, 2)}\n`)
  inputs.set('prompts.jsonl', `${promptRows(bench.manifest).map((row) => JSON.stringify(row)).join('\n')}\n`)
  return inputs
}

/** Write the fixture tree plus the manifest and prompts an arm needs. */
async function writeArmInputs(root: string, bench: GeneratedBench): Promise<void> {
  for (const [path, content] of armInputs(bench)) await writeOut(join(root, path), content)
}

/**
 * A fixture directory is usable only when it still holds the generated bytes.
 * Scoring an arm against a tree the arm could have rewritten would grade the
 * tree, not the arm. This covers every file the runner wrote, the sessions plus
 * `manifest.json` and `prompts.jsonl`, so an arm cannot quietly reword its own
 * prompts either. Files the arm added are left alone: scoring reads the session
 * paths from the manifest it just generated, never from the directory listing,
 * so a file the generator did not write is never read.
 */
async function assertUnmodified(root: string, bench: GeneratedBench): Promise<void> {
  for (const [file, content] of armInputs(bench)) {
    const actual = await readFile(join(root, file), 'utf8').catch(() => undefined)
    if (actual === undefined) throw new Error(`fixture directory is missing ${file}`)
    if (actual !== content) throw new Error(`fixture file differs from the generated bytes: ${file}`)
  }
}

async function main(argv: readonly string[]): Promise<number> {
  const [command, ...rest] = argv
  if (command === '--help' || command === '-h') {
    console.log(USAGE)
    return 0
  }
  if (!command) {
    // Every other failure path writes to stderr, so this one does too.
    console.error(USAGE)
    return 1
  }
  const { positional, flags } = parseArgs(rest)
  const bench = generateBench()

  if (command === 'fixtures') {
    const out = flags.get('out')
    if (!out) throw new Error('fixtures needs --out <dir>')
    await writeArmInputs(out, bench)
    console.log(`wrote ${bench.files.length} session files, manifest.json and prompts.jsonl to ${out}`)
    return 0
  }

  if (command === 'gold') {
    const out = flags.get('out')
    if (!out) throw new Error('gold needs --out <file.json>')
    await writeOut(out, `${JSON.stringify(bench.gold, null, 2)}\n`)
    console.log(`wrote gold answers for ${Object.keys(bench.gold).length} questions to ${out}`)
    return 0
  }

  if (command === 'score') {
    const answersPath = positional[0]
    if (!answersPath) throw new Error('score needs an answers JSON path')
    const file = parseAnswersFile(JSON.parse(await readFile(answersPath, 'utf8')) as unknown)
    let root = flags.get('fixtures')
    if (root) await assertUnmodified(root, bench)
    else {
      root = await mkdtemp(join(tmpdir(), 'traces-bench-audit-'))
      await writeFixtures(root, bench)
    }
    const index = await loadCitationIndex(root, bench.manifest)
    const score = scoreArm(file, bench.gold, index)
    const report = renderArmScore(score)
    const out = flags.get('out')
    if (out) await writeOut(out, report)
    else console.log(report)
    const json = flags.get('json')
    if (json) await writeOut(json, `${JSON.stringify(score, null, 2)}\n`)
    return 0
  }

  if (command === 'arm') {
    const arm = flags.get('arm') as ArmName | undefined
    const out = flags.get('out')
    if (!arm || !ARMS.includes(arm)) throw new Error(`arm needs --arm ${ARMS.join('|')}`)
    if (!out) throw new Error('arm needs --out <answers.json>')
    const variants = flags.get('variants') ?? 'canonical'
    if (variants !== 'canonical' && variants !== 'all') throw new Error('--variants is canonical or all')
    const work = flags.get('work') ?? await mkdtemp(join(tmpdir(), `traces-bench-${arm}-`))
    let root = flags.get('fixtures')
    if (root) await assertUnmodified(root, bench)
    else {
      root = join(work, 'fixtures')
      await writeArmInputs(root, bench)
    }
    const file = await runArm({
      arm,
      root: resolve(root),
      manifest: bench.manifest,
      cli: resolve(flags.get('traces') ?? DIST_CLI),
      work: resolve(work),
      model: flags.get('model'),
      budgetUsd: flags.has('budget-usd') ? Number(flags.get('budget-usd')) : undefined,
      questions: flags.get('questions')?.split(','),
      variants,
      concurrency: flags.has('concurrency') ? Number(flags.get('concurrency')) : undefined,
      log: (line) => console.error(line),
    })
    await writeOut(out, `${JSON.stringify(file, null, 2)}\n`)
    const cost = file.answers.reduce((total, row) => total + (row.cost_usd ?? 0), 0)
    console.log(`wrote ${file.answers.length} ${arm} answers to ${out} ($${cost.toFixed(4)})`)
    return 0
  }

  throw new Error(`unknown command ${command}\n${USAGE}`)
}

main(process.argv.slice(2)).then(
  (code) => {
    process.exitCode = code
  },
  (error: unknown) => {
    console.error(error instanceof Error ? error.message : String(error))
    process.exitCode = 1
  },
)
